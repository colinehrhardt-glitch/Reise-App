const ARROW_SPACING = 24;
const ARROW_LIMIT = 2500;
const ARROW_SHAPE = [[-7, -6], [1, -6], [8, 0], [1, 6], [-7, 6], [-1.5, 0]];
const TERMINAL_ICONS = { airport: 'flight', bus_station: 'bus', train_station: 'train', ferry_terminal: 'ferry' };
let routeData = null;
let routeRedraw = 0;

function terminalIcon(terminal) {
  const full = String(terminal.iata || terminal.label || '').replace(/[<>&"]/g, '');
  const label = terminal.iata || map.getZoom() >= 12 ? full : '';
  return L.divIcon({
    className: 'marker-icon',
    html: `<div class="route-terminal route-terminal--${terminal.kind}"><span class="route-terminal__dot"></span><span class="route-terminal__label${label ? '' : ' is-compact'}">${svg(TERMINAL_ICONS[terminal.kind] || 'place')}${label ? `<span>${label}</span>` : ''}</span></div>`,
    iconSize: [12, 12],
    iconAnchor: [6, 6]
  });
}

function arrowRings(coords) {
  if (!Array.isArray(coords) || coords.length < 2) return [];
  const size = map.getSize();
  const pad = 200;
  const view = L.bounds(map.containerPointToLayerPoint([-pad, -pad]), map.containerPointToLayerPoint([size.x + pad, size.y + pad]));
  const points = coords.map((point) => map.latLngToLayerPoint(point));
  let total = 0;
  for (let i = 1; i < points.length; i += 1) total += points[i - 1].distanceTo(points[i]);
  const rings = [];
  if (total < 4) return rings;
  const spacing = total < ARROW_SPACING * 1.5 ? total : ARROW_SPACING;
  let next = total < ARROW_SPACING * 1.5 ? total / 2 : ARROW_SPACING / 2;
  let travelled = 0;
  for (let i = 1; i < points.length && rings.length < ARROW_LIMIT; i += 1) {
    const a = points[i - 1];
    const b = points[i];
    const step = a.distanceTo(b);
    if (step === 0) continue;
    const angle = Math.atan2(b.y - a.y, b.x - a.x);
    const cos = Math.cos(angle);
    const sin = Math.sin(angle);
    while (next <= travelled + step && rings.length < ARROW_LIMIT) {
      const f = (next - travelled) / step;
      const x = a.x + (b.x - a.x) * f;
      const y = a.y + (b.y - a.y) * f;
      if (view.contains([x, y])) {
        rings.push(ARROW_SHAPE.map(([px, py]) => map.layerPointToLatLng([x + px * cos - py * sin, y + px * sin + py * cos])));
      }
      next += spacing;
    }
    travelled += step;
  }
  return rings;
}

function drawRoute() {
  routeLayer.clearLayers();
  if (!routeData) return;
  const { points, legs, selected, stays } = routeData;
  for (const stay of stays || []) {
    const marker = L.marker([stay.lat, stay.lon], {
      icon: L.divIcon({ className: 'marker-icon', html: `<div class="route-stay">${svg('hotel')}<span class="route-stay__check">${svg('check')}</span></div>`, iconSize: [30, 30], iconAnchor: [15, 15] }),
      keyboard: false,
      zIndexOffset: 1100,
      title: `${stay.name} · ${stay.stop}`
    }).addTo(routeLayer);
    marker.on('click', () => routeHandlers.onStayClick?.(stay));
  }
  const hasSelection = Number.isInteger(selected) && legs[selected];
  legs.forEach((leg, index) => {
    if (!leg) return;
    const style = ROUTE_MODES[leg.mode] || ROUTE_MODES.car;
    const dim = hasSelection && index !== selected;
    const pick = () => routeHandlers.onLegClick?.(index);
    const hitCoords = Array.isArray(leg.segments) && leg.segments.length ? leg.segments.flatMap((segment) => segment.coords || []) : leg.coords;
    if (Array.isArray(hitCoords) && hitCoords.length > 1) {
      L.polyline(hitCoords, { renderer: routeRenderer, color: '#000', opacity: 0, weight: 26, lineCap: 'round', className: 'route-hit' }).addTo(routeLayer).on('click', pick);
    }
    if (hasSelection && index === selected && Array.isArray(hitCoords) && hitCoords.length > 1) {
      L.polyline(hitCoords, { renderer: routeRenderer, color: style.color, opacity: 0.22, weight: 16, lineCap: 'round', interactive: false }).addTo(routeLayer);
    }
    const segments = Array.isArray(leg.segments) && leg.segments.length ? leg.segments : [{ coords: leg.coords, kind: 'main' }];
    for (const segment of segments) {
      if (!Array.isArray(segment.coords) || segment.coords.length < 2) continue;
      if (segment.kind === 'ground') {
        const line = L.polyline(segment.coords, {
          renderer: routeRenderer,
          color: '#495057',
          weight: 3.5,
          opacity: dim ? 0.35 : 0.8,
          dashArray: '1 8',
          lineCap: 'round'
        }).addTo(routeLayer);
        line.on('click', pick);
        continue;
      }
      const rings = arrowRings(segment.coords);
      if (!rings.length) continue;
      const arrows = L.polygon(rings, {
        renderer: routeRenderer,
        color: '#ffffff',
        weight: 1.6,
        fillColor: style.color,
        fillOpacity: (leg.estimate ? 0.6 : 1) * (dim ? 0.4 : 1),
        opacity: dim ? 0.5 : 1,
        smoothFactor: 0,
        noClip: true,
        lineJoin: 'round'
      }).addTo(routeLayer);
      arrows.on('click', pick);
    }
    for (const terminal of leg.terminals || []) {
      if (!terminal) continue;
      L.marker([terminal.lat, terminal.lon], { icon: terminalIcon(terminal), keyboard: false, zIndexOffset: 1000, title: terminal.name || terminal.label || '' }).addTo(routeLayer);
    }
  });
  points.forEach((point, index) => {
    const marker = L.marker([point.lat, point.lon], {
      icon: stopIcon(point.label, point.start),
      keyboard: false,
      zIndexOffset: 1200,
      title: point.name || ''
    }).addTo(routeLayer);
    marker.on('click', () => routeHandlers.onStopClick?.(index));
  });
}

function scheduleRouteRedraw() {
  if (!routeData) return;
  cancelAnimationFrame(routeRedraw);
  routeRedraw = requestAnimationFrame(drawRoute);
}

export function renderRoute(points, legs, selected = null, stays = []) {
  routeData = { points, legs, selected, stays };
  drawRoute();
}

export function fitCoords(coords, maxZoom = 14) {
  const valid = coords.filter((point) => Array.isArray(point) && Number.isFinite(point[0]) && Number.isFinite(point[1]));
  if (!valid.length) return;
  if (valid.length === 1) {
    moveTo(valid[0], Math.max(map.getZoom(), 12));
    return;
  }
  const bounds = L.latLngBounds(valid);
  map.flyToBounds(bounds, {
    paddingTopLeft: [insets.left + 36, insets.top + 36],
    paddingBottomRight: [Math.max(insets.right, 64) + 24, insets.bottom + 36],
    maxZoom,
    duration: 0.8
  });
}

