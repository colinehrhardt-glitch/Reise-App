export function getBounds() {
  const size = map.getSize();
  const topLeft = map.containerPointToLatLng([insets.left, insets.top]);
  const bottomRight = map.containerPointToLatLng([size.x - insets.right, Math.max(insets.top + 1, size.y - insets.bottom)]);
  const west = Math.max(-180, L.Util.wrapNum(topLeft.lng, [-180, 180], true));
  let east = Math.min(180, L.Util.wrapNum(bottomRight.lng, [-180, 180], true));
  if (east < west) east = 180;
  return {
    south: Math.max(-90, bottomRight.lat),
    north: Math.min(90, topLeft.lat),
    west,
    east
  };
}

export function getVisibleCenter() {
  const size = map.getSize();
  const point = L.point(
    insets.left + (size.x - insets.left - insets.right) / 2,
    insets.top + (size.y - insets.top - insets.bottom) / 2
  );
  const latlng = map.containerPointToLatLng(point).wrap();
  return { lat: latlng.lat, lon: latlng.lng };
}

function centerFor(latlng, zoom) {
  const offset = L.point((insets.left - insets.right) / 2, (insets.top - insets.bottom) / 2);
  const projected = map.project(latlng, zoom).subtract(offset);
  return map.unproject(projected, zoom);
}

function moveTo(latlng, zoom, animate = true) {
  return new Promise((resolve) => {
    const target = centerFor(L.latLng(latlng), zoom);
    const already = map.getZoom() === zoom && map.latLngToContainerPoint(target).distanceTo(map.latLngToContainerPoint(map.getCenter())) < 2;
    if (already) {
      resolve();
      return;
    }
    map.once('moveend', () => resolve());
    if (animate) map.flyTo(target, zoom, { duration: 0.7 });
    else map.setView(target, zoom, { animate: false });
  });
}

export function flyToLocation(lat, lon, zoom, animate = true) {
  return moveTo([lat, lon], zoom, animate);
}

export function zoomInTo(minZoom) {
  return moveTo(map.getCenter(), Math.max(minZoom, map.getZoom() + 1));
}

const CITY_KINDS = ['city', 'municipality', 'city_district', 'borough'];
const TOWN_KINDS = ['town', 'suburb', 'quarter'];
const VILLAGE_KINDS = ['village', 'hamlet', 'neighbourhood', 'isolated_dwelling', 'locality'];

function spanKm(bounds) {
  const a = L.latLng(bounds.south, bounds.west);
  const b = L.latLng(bounds.north, bounds.east);
  return a.distanceTo(b) / 1000;
}

function cityZoom() {
  const size = map.getSize();
  const width = size.x - insets.left - insets.right;
  const height = size.y - insets.top - insets.bottom;
  const extra = Math.round(Math.log2(Math.max(width, height, 1) / 520));
  return Math.min(15, Math.max(13, 13 + extra));
}

export function searchResultZoom(result) {
  if (VILLAGE_KINDS.includes(result.kind)) return Math.max(15, cityZoom());
  if (TOWN_KINDS.includes(result.kind)) return Math.max(14, cityZoom());
  if (CITY_KINDS.includes(result.kind)) return cityZoom();
  if (result.rank >= 26) return 17;
  if (result.rank >= 20) return Math.max(15, cityZoom());
  if (result.rank >= 17) return Math.max(14, cityZoom());
  if (result.rank >= 11) return cityZoom();
  if (result.bounds && spanKm(result.bounds) <= 60) return cityZoom();
  return null;
}

export function boundsAt(lat, lon, zoom) {
  const size = map.getSize();
  const origin = map.project(centerFor(L.latLng(lat, lon), zoom), zoom).subtract(size.divideBy(2));
  const topLeft = map.unproject(origin.add([insets.left, insets.top]), zoom);
  const bottomRight = map.unproject(origin.add([size.x - insets.right, Math.max(insets.top + 1, size.y - insets.bottom)]), zoom);
  return {
    south: Math.max(-90, bottomRight.lat),
    north: Math.min(90, topLeft.lat),
    west: Math.max(-180, topLeft.lng),
    east: Math.min(180, bottomRight.lng)
  };
}

export function planSearchResult(result) {
  const zoom = searchResultZoom(result);
  if (zoom === null) return null;
  return { zoom, bounds: boundsAt(result.lat, result.lon, zoom), center: { lat: result.lat, lon: result.lon } };
}

export function showSearchResult(result) {
  const zoom = searchResultZoom(result);
  if (zoom !== null || !result.bounds) return moveTo([result.lat, result.lon], zoom ?? 13);
  return new Promise((resolve) => {
    const bounds = L.latLngBounds([result.bounds.south, result.bounds.west], [result.bounds.north, result.bounds.east]);
    map.once('moveend', () => resolve());
    map.flyToBounds(bounds, {
      paddingTopLeft: [insets.left + 16, insets.top + 16],
      paddingBottomRight: [insets.right + 16, insets.bottom + 16],
      maxZoom: 14,
      duration: 0.9
    });
  });
}

